import os
from datetime import datetime

def generate_markdown_report(results, output_filename="SOC_Triage_Report.md"):
    """
    دالة لتوليد تقرير بصيغة Markdown يحتوي على نتائج فحص الـ IOCs
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    report_content = f"""# 🛡️ Automated SOC Alert Triage Report
**Generated on:** `{timestamp}`  
**Tool:** SOC-Triage-Toolkit  

---

## 📊 Executive Summary
This report contains the automated threat intelligence enrichment results for the submitted Indicators of Compromise (IOCs) via VirusTotal API.

| IOC Value | Type / Status | Malicious 🚨 | Suspicious ⚠️ | Harmless ✅ |
| :--- | :--- | :---: | :---: | :---:
"""

    for res in results:
        ioc = res.get("ioc", "N/A")
        status = res.get("status", "Unknown")
        
        if status == "Success":
            malicious = res.get("malicious", 0)
            suspicious = res.get("suspicious", 0)
            harmless = res.get("harmless", 0)
            
            # تمييز بصري لو فيه خطر حقيقي
            mal_label = f"🔴 **{malicious}**" if malicious > 0 else f"🟢 {malicious}"
            
            report_content += f"| `{ioc}` | Success | {mal_label} | {suspicious} | {harmless} |\n"
        else:
            report_content += f"| `{ioc}` | Failed / Not Found | - | - | - |\n"

    report_content += f"""
---
> *Report automatically generated by Shrouq's SOC-Triage-Toolkit.*
"""

    # حفظ التقرير في ملف Markdown
    with open(output_filename, "w", encoding="utf-8") as f:
        f.write(report_content)
        
    print(f"\n[+] Triage report successfully generated: {output_filename}")
